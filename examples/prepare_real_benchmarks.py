"""Prepare real experimental RCSB PDB and AlphaFold DB benchmark files for biophys-guard."""

from __future__ import annotations

from pathlib import Path
import shutil
from typing import Iterable, Optional, Set


def _filter_pdb_chains(
    src_pdb: Path,
    dst_pdb: Path,
    keep_chains: Optional[Set[str]] = None,
    backbone_only: bool = False,
    remarks: Optional[Iterable[str]] = None,
) -> Path:
    lines = src_pdb.read_text(encoding="utf-8", errors="replace").splitlines()
    out_lines = list(remarks or [])
    bb_names = {"N", "CA", "C", "O"}

    for line in lines:
        rec = line[:6].strip()
        if rec in {"HEADER", "TITLE", "COMPND", "EXPDTA"} and not backbone_only:
            out_lines.append(line)
            continue
        if rec == "ATOM":
            ch = line[21:22]
            if keep_chains is not None and ch not in keep_chains:
                continue
            if backbone_only:
                atom_name = line[12:16].strip()
                if atom_name not in bb_names:
                    continue
            out_lines.append(line)
        elif rec == "TER":
            if len(line) > 21 and keep_chains is not None and line[21:22] not in keep_chains:
                continue
            out_lines.append(line)

    out_lines.append("END")
    dst_pdb.parent.mkdir(parents=True, exist_ok=True)
    dst_pdb.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    return dst_pdb


def prepare_benchmarks(output_dir: str | Path = "examples") -> dict[str, Path]:
    """Extract clean real-structure benchmark files from RCSB PDB and AlphaFold DB downloads."""
    out = Path(output_dir)
    real_dir = out / "real_structures"

    ubq_pdb = real_dir / "pdb" / "pdb_00001ubq.pdb"
    ubq_cif = real_dir / "mmcif" / "pdb_00001ubq.cif"
    s5b_pdb = real_dir / "pdb" / "pdb_00007s5b.pdb"
    jzu_pdb = real_dir / "pdb" / "pdb_00007jzu.pdb"
    jzl_pdb = real_dir / "pdb" / "pdb_00007jzl.pdb"
    n8z_pdb = real_dir / "pdb" / "pdb_00001n8z.pdb"
    af_p53 = real_dir / "afdb" / "AF-P04637-F1-model_v6.cif"

    created: dict[str, Path] = {}

    if ubq_pdb.exists():
        created["1ubq_pdb"] = _filter_pdb_chains(ubq_pdb, out / "1UBQ_ubiquitin.pdb", keep_chains={"A"})
    if ubq_cif.exists():
        dst = out / "1UBQ_ubiquitin.cif"
        shutil.copyfile(ubq_cif, dst)
        created["1ubq_cif"] = dst
    if s5b_pdb.exists():
        created["7s5b_monomer"] = _filter_pdb_chains(s5b_pdb, out / "7S5B_il7r_binder.pdb", keep_chains={"A"})
    if jzu_pdb.exists():
        created["7jzu_lcb1_monomer"] = _filter_pdb_chains(jzu_pdb, out / "7JZU_LCB1_monomer.pdb", keep_chains={"A"})
        created["7jzu_lcb1_complex"] = _filter_pdb_chains(jzu_pdb, out / "7JZU_LCB1_RBD_complex.pdb", keep_chains={"A", "B"})
        created["7jzu_backbone_only"] = _filter_pdb_chains(
            jzu_pdb,
            out / "7JZU_LCB1_backbone_only.pdb",
            keep_chains={"A"},
            backbone_only=True,
            remarks=["REMARK   1 GENERATED BY RFDIFFUSION BACKBONE-ONLY TEST (STRIPPED FROM 7JZU CHAIN A)"],
        )
    if jzl_pdb.exists():
        created["7jzl_cb_stub"] = _filter_pdb_chains(jzl_pdb, out / "7JZL_LCB1_cb_stub.pdb", keep_chains={"E"})
    if n8z_pdb.exists():
        created["1n8z_fab"] = _filter_pdb_chains(n8z_pdb, out / "1N8Z_Trastuzumab_Fab.pdb", keep_chains={"A", "B"})
    if af_p53.exists():
        dst = out / "AF_P04637_p53.cif"
        shutil.copyfile(af_p53, dst)
        created["af_p53"] = dst

    return created


if __name__ == "__main__":
    res = prepare_benchmarks(Path(__file__).resolve().parent)
    for k, v in res.items():
        print(f"Prepared {k}: {v}")
